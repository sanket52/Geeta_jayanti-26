create or replace function public.complete_student_registration(p_data jsonb)
returns table(registration_number text,status text)
language plpgsql security definer set search_path=''
as $$
declare v_uid uuid := (p_data->>'userId')::uuid; v_email text; v_id uuid; v_num text; v_status text;
begin
  if (select auth.role()) <> 'service_role' then raise exception 'Registration must use the secure registration service' using errcode='42501'; end if;
  if coalesce((p_data->>'privacyConsent')::boolean,false) is not true then raise exception 'Registration privacy consent is required'; end if;
  -- The Edge Function validates the Supabase Auth session and verified email
  -- before calling this service-role-only RPC.
  v_email := lower(trim(coalesce(p_data->>'email','')));
  if coalesce((p_data->>'emailVerified')::boolean,false) is not true or v_email = '' then raise exception 'A verified matching email is required'; end if;
  if length(trim(coalesce(p_data->>'fullName',''))) not between 2 and 160 or length(trim(coalesce(p_data->>'fatherName',''))) not between 2 and 160 then raise exception 'Enter the participant and father names'; end if;
  if (p_data->>'gender') not in ('Female','Male','Other','Prefer not to say') then raise exception 'Select a valid gender'; end if;
  if length(trim(coalesce(p_data->>'mobile',''))) not between 7 and 30 or (p_data->>'mobile') !~ '^\+?[0-9 ()-]{7,20}$' then raise exception 'Enter a valid mobile number'; end if;
  if coalesce(trim(p_data->>'alternateMobile'),'') <> '' and (p_data->>'alternateMobile') !~ '^\+?[0-9 ()-]{7,20}$' then raise exception 'Enter a valid alternate mobile number'; end if;
  if length(trim(coalesce(p_data->>'schoolName',''))) not between 2 and 200 or length(trim(coalesce(p_data->>'educationLevel',''))) not between 1 and 80 then raise exception 'Enter a valid school and class/course'; end if;
  if length(trim(coalesce(p_data->>'house',''))) = 0 or length(trim(coalesce(p_data->>'street',''))) = 0 or length(trim(coalesce(p_data->>'city',''))) = 0 then raise exception 'Complete the required address fields'; end if;
  if length(trim(coalesce(p_data->>'accountHolder',''))) not between 2 and 160 or length(trim(coalesce(p_data->>'bankName',''))) not between 2 and 160 then raise exception 'Enter valid bank account holder and bank names'; end if;
  if coalesce(p_data->>'country','') <> 'India' then raise exception 'Select India as the registration country'; end if;
  if (p_data->>'birthDate')::date > date '2026-12-20' then raise exception 'Enter a valid date of birth'; end if;
  if (date '2026-12-20' - (p_data->>'birthDate')::date) / 365.2425 < 18 and coalesce((p_data->>'parentalConsent')::boolean,false) is not true then raise exception 'Parent or guardian consent is required'; end if;
  if not exists(select 1 from public.gjm_india_districts d where d.state=p_data->>'state' and d.district=p_data->>'district') then raise exception 'Select a valid state and district'; end if;
  if coalesce(p_data->>'photoPath','') not like v_uid::text || '/%' or coalesce(p_data->>'aadhaarPath','') not like v_uid::text || '/%' then raise exception 'Private document ownership is invalid'; end if;
  if coalesce(p_data->>'photoType','') not in ('image/jpeg','image/png') or (p_data->>'photoSize')::bigint not between 1 and 2097152 or (p_data->>'aadhaarSize')::bigint not between 1 and 5242880 then raise exception 'Document type or size is invalid'; end if;
  if length(coalesce(p_data->>'pin','')) <> 6 or (p_data->>'pin') !~ '^[0-9]{6}$' then raise exception 'Enter a valid six digit PIN code'; end if;
  if (p_data->>'ifsc') !~* '^[A-Z]{4}0[A-Z0-9]{6}$' then raise exception 'Enter a valid IFSC code'; end if;
  if length(coalesce(p_data->>'accountNumber','')) not between 9 and 18 or (p_data->>'accountNumber') !~ '^[0-9]+$' then raise exception 'Enter a valid bank account number'; end if;
  if jsonb_array_length(coalesce(p_data->'selectedCompetitions','[]'::jsonb)) not between 1 and 2 then raise exception 'Choose one or two competition categories'; end if;
  if exists (
    select 1 from jsonb_array_elements_text(p_data->'selectedCompetitions') c
    where not exists(select 1 from public.gjm_competitions g where g.code=c and g.is_open)
  ) then raise exception 'A selected competition is unavailable'; end if;
  if exists(select 1 from public.candidate_registrations where user_id=v_uid) then raise exception 'A registration already exists for this account'; end if;
  insert into public.candidate_registrations(user_id,email,full_name,mobile,school_name,education_level,city,state,birth_date,parental_consent,selected_competition_codes,father_name,mother_name,gender,alternate_mobile,house_building,street_locality,country,district,pin_code,email_verified_at,privacy_consent_at,bank_account_last4)
  values(v_uid,v_email,p_data->>'fullName',p_data->>'mobile',p_data->>'schoolName',p_data->>'educationLevel',p_data->>'city',p_data->>'state',(p_data->>'birthDate')::date,coalesce((p_data->>'parentalConsent')::boolean,false),array(select jsonb_array_elements_text(p_data->'selectedCompetitions')),p_data->>'fatherName',nullif(p_data->>'motherName',''),p_data->>'gender',nullif(p_data->>'alternateMobile',''),p_data->>'house',p_data->>'street',p_data->>'country',p_data->>'district',p_data->>'pin',now(),now(),right(p_data->>'accountNumber',4)) returning id,registration_number,status into v_id,v_num,v_status;
  insert into private.candidate_bank_details(registration_id,account_ciphertext,account_iv,account_holder,bank_name,ifsc,branch)
  values(v_id,p_data->>'accountCiphertext',p_data->>'accountIv',p_data->>'accountHolder',p_data->>'bankName',p_data->>'ifsc',nullif(p_data->>'branch',''));
  insert into public.gjm_registration_documents(registration_id,user_id,kind,storage_path,content_type,file_size)
  values(v_id,v_uid,'photo',p_data->>'photoPath',p_data->>'photoType',(p_data->>'photoSize')::bigint),
    (v_id,v_uid,'aadhaar',p_data->>'aadhaarPath','application/pdf',(p_data->>'aadhaarSize')::bigint);
  return query select v_num,v_status;
end;
$$;
revoke all on function public.complete_student_registration(jsonb) from public,anon;
revoke execute on function public.complete_student_registration(jsonb) from authenticated;
grant execute on function public.complete_student_registration(jsonb) to service_role;

-- Permit the trusted service role to create the row after it has independently
-- verified the user's access token and email confirmation in the Edge Function.
create or replace function private.assign_candidate_registration()
returns trigger language plpgsql security definer set search_path=''
as $$
begin
  if new.user_id is distinct from (select auth.uid()) and (select auth.role()) <> 'service_role' then
    raise exception 'Registration must belong to the signed-in user';
  end if;
  if (select auth.role()) = 'service_role' then
    new.email := lower(trim(new.email));
  else
    new.email := lower(trim(coalesce(auth.jwt()->>'email','')));
  end if;
  if new.email = '' then raise exception 'A verified email address is required'; end if;
  new.registration_number := 'GJM26-' || lpad(nextval('private.candidate_registration_number_seq')::text,6,'0');
  return new;
end;
$$;
